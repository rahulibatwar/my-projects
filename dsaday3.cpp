#include  <bits/stdc++.h>
using namespace std;

int main() { 
    // int a = 3, b = 7;
    cout << (6 & 10) << endl; // Bitwise AND
    cout << (6 | 10) << endl; // Bitwise OR
    cout << (6 ^ 10) << endl; // Bitwise XOR
    cout << (10 << 2) << endl; // Left Shift
    cout << (10 >> 1) << endl; // Right Shift

    return 0;
}